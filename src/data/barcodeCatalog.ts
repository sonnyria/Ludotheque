/**
 * Normalizes barcode input (stripping non-digits) and looks up
 * variations (12 vs 13 digits, with/without leading 0).
 */
export function lookupBarcodeInCatalog(rawCode: string): CatalogGame | null {
  if (!rawCode) return null;
  const clean = rawCode.replace(/\D/g, '').trim();
  if (!clean) return null;

  // 1. Direct match
  if (BARCODE_CATALOG[clean]) {
    return BARCODE_CATALOG[clean];
  }

  // 2. 12-digit UPC padded with 0 to 13-digit EAN
  if (BARCODE_CATALOG['0' + clean]) {
    return BARCODE_CATALOG['0' + clean];
  }

  // 3. Padded with 00 to 14-digit GTIN
  if (BARCODE_CATALOG['00' + clean]) {
    return BARCODE_CATALOG['00' + clean];
  }

  // 4. 13-digit EAN stripped to 12-digit UPC
  if (clean.startsWith('0') && BARCODE_CATALOG[clean.slice(1)]) {
    return BARCODE_CATALOG[clean.slice(1)];
  }

  // 5. 14-digit GTIN stripped of 00
  if (clean.startsWith('00') && BARCODE_CATALOG[clean.slice(2)]) {
    return BARCODE_CATALOG[clean.slice(2)];
  }

  // 6. Strip all leading zeros
  const unpadded = clean.replace(/^0+/, '');
  if (unpadded && BARCODE_CATALOG[unpadded]) {
    return BARCODE_CATALOG[unpadded];
  }

  // 7. Check across all keys by unpadded comparison
  if (unpadded.length >= 7) {
    for (const [key, val] of Object.entries(BARCODE_CATALOG)) {
      if (key.replace(/^0+/, '') === unpadded) {
        return val;
      }
    }
  }

  return null;
}

/**
 * Searches the catalog by title or keywords (instant 0ms resolution).
 */
export function findGameInCatalog(query: string, preferredConsole?: string): CatalogGame | undefined {
  if (!query || !query.trim()) return undefined;
  const q = query.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');

  const entries = Object.values(BARCODE_CATALOG);

  // Exact match first
  for (const g of entries) {
    const t = g.title.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (t === q && (!preferredConsole || preferredConsole === 'Autre' || g.console === preferredConsole)) {
      return g;
    }
  }

  // Starts with match
  for (const g of entries) {
    const t = g.title.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (t.startsWith(q) && (!preferredConsole || preferredConsole === 'Autre' || g.console === preferredConsole)) {
      return g;
    }
  }

  // Substring match
  for (const g of entries) {
    const t = g.title.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (t.includes(q) && (!preferredConsole || preferredConsole === 'Autre' || g.console === preferredConsole)) {
      return g;
    }
  }

  // Fallback: any matching substring even across platforms
  for (const g of entries) {
    const t = g.title.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (t.includes(q)) {
      return g;
    }
  }

  return undefined;
}
